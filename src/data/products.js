// ── Helpers ─────────────────────────────────────────────
export const getProductBySlug = (slug) => products.find((p) => p.slug === slug)

export const getDepartment = (key) => DEPARTMENTS.find((d) => d.key === key)

export const getCategory = (deptKey, catKey) =>
  getDepartment(deptKey)?.categories.find((c) => c.key === catKey)

export const formatPKR = (n) => 'Rs ' + Number(n).toLocaleString('en-PK')
